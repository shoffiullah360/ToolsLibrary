import fs from 'node:fs';
import path from 'node:path';
import { cluster1Presets } from './presets-data/cluster1.mjs';
import { cluster2Presets } from './presets-data/cluster2.mjs';
import { cluster3Presets } from './presets-data/cluster3.mjs';
import { cluster4Presets } from './presets-data/cluster4.mjs';
import { cluster5Presets } from './presets-data/cluster5.mjs';
import { cluster6Presets } from './presets-data/cluster6.mjs';
import { countWords, countEditorialWords } from './presets-data/helper.mjs';

const allPresets = [
  ...cluster1Presets,
  ...cluster2Presets,
  ...cluster3Presets,
  ...cluster4Presets,
  ...cluster5Presets,
  ...cluster6Presets
];

console.log(`Auditing ${allPresets.length} presets...`);

const targetSlugs = [
  'how-to-remove-empty-lines-in-notepad-plus-plus',
  'how-to-remove-empty-lines-in-excel',
  'how-to-remove-empty-lines-in-word',
  'how-to-remove-empty-lines-in-google-docs',
  'how-to-remove-empty-lines-in-vscode',
  'how-to-remove-empty-lines-in-google-sheets',
  'how-to-remove-empty-lines-in-vim',
  'notepad-plus-plus-remove-empty-lines',
  'notepad-plus-plus-remove-all-empty-lines',
  'word-document-remove-empty-lines',
  'google-docs-remove-empty-lines',
  'sublime-text-remove-empty-lines',
  'ultraedit-remove-empty-lines',
  'windows-notepad-remove-empty-lines',
  'vscode-remove-empty-lines',
  'visual-studio-remove-empty-lines',
  'intellij-remove-empty-lines',
  'vim-remove-empty-lines',
  'eclipse-remove-empty-lines',
  'webstorm-remove-empty-lines',
  'remove-empty-lines-excel',
  'google-sheets-remove-empty-lines',
  'remove-empty-lines-csv',
  'libreoffice-calc-remove-empty-lines',
  'remove-empty-lines-in-json',
  'remove-empty-lines-in-xml',
  'remove-empty-lines-python-string',
  'remove-empty-lines-javascript',
  'remove-empty-lines-sql-query',
  'remove-empty-lines-from-text-file',
  'remove-empty-lines-online-tool',
  'regex-remove-empty-lines',
  'remove-whitespace-only-lines',
  'collapse-multiple-blank-lines-to-one',
  'remove-leading-trailing-empty-lines'
];

let failed = false;

// Check exact slugs
for (let i = 0; i < targetSlugs.length; i++) {
  const expectedSlug = targetSlugs[i];
  const actualPreset = allPresets[i];
  if (!actualPreset || actualPreset.slug !== expectedSlug) {
    console.error(`Index ${i} slug mismatch: expected ${expectedSlug}, got ${actualPreset?.slug}`);
    failed = true;
  }
}

// Audit word counts and FAQs
for (const p of allPresets) {
  const intentWords = countWords(p.intentCard);
  const edWords = countEditorialWords(p.editorialGuide);
  if (intentWords < 50 || intentWords > 60) {
    console.error(`Slug ${p.slug} Intent words out of range (50-60): ${intentWords}`);
    failed = true;
  }
  if (edWords < 600) {
    console.error(`Slug ${p.slug} Editorial words below 600: ${edWords}`);
    failed = true;
  }
  if (p.faqs.length !== 6) {
    console.error(`Slug ${p.slug} FAQs count != 6: ${p.faqs.length}`);
    failed = true;
  }
}

if (failed) {
  console.error('Audit failed!');
  process.exit(1);
}

console.log('Audit 100% PASSED! Generating src/data/removeEmptyLinesPresets.ts...');

const tsContent = `// Autogenerated 35 High-Intent Remove Empty Lines Presets
export interface EditorialSection {
  title: string;
  paragraphs: string[];
  bullets?: string[];
  callout?: {
    type: 'tip' | 'note' | 'warning';
    label: string;
    text: string;
  };
}

export interface RemoveEmptyLinesPreset {
  slug: string;
  cluster: string;
  clusterTitle: string;
  primaryQuery: string;
  h1: string;
  metaTitle: string;
  metaDescription: string;
  subtitle: string;
  intentCard: string;
  options: {
    whitespaceOnly: boolean;
    collapseBlanks: boolean;
    trimEdges: boolean;
  };
  sampleText: string;
  editorialGuide: {
    heading: string;
    sections: EditorialSection[];
  };
  faqs: Array<{
    question: string;
    answer: string;
  }>;
}

export const REMOVE_EMPTY_LINES_PRESETS: RemoveEmptyLinesPreset[] = ${JSON.stringify(allPresets, null, 2)};

export function getRemoveEmptyLinesPreset(slug: string): RemoveEmptyLinesPreset | undefined {
  return REMOVE_EMPTY_LINES_PRESETS.find((p) => p.slug === slug);
}
`;

fs.writeFileSync(path.resolve('./src/data/removeEmptyLinesPresets.ts'), tsContent, 'utf8');
console.log('Successfully wrote src/data/removeEmptyLinesPresets.ts!');
