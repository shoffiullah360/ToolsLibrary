import fs from 'fs';
import path from 'path';

// Helper to recursively find all files in a directory
function getFiles(dir, ext = '.html') {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(getFiles(fullPath, ext));
    } else if (file.endsWith(ext)) {
      results.push(fullPath);
    }
  }
  return results;
}

const distDir = 'dist';
const allHtmlFiles = getFiles(distDir, '.html');
console.log(`Found ${allHtmlFiles.length} total HTML files in ${distDir}/`);

// Load Sitemap URLs
const sitemapXml = fs.readFileSync(path.join(distDir, 'sitemap-0.xml'), 'utf-8');
const sitemapUrls = new Set([...sitemapXml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => m[1]));
console.log(`Loaded ${sitemapUrls.size} URLs from sitemap-0.xml`);

// Load _redirects
const redirectsPath = path.join('public', '_redirects');
const redirectsRaw = fs.readFileSync(redirectsPath, 'utf-8');
const redirectRules = [];
const exactRedirects = new Map();

for (const line of redirectsRaw.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const parts = trimmed.split(/\s+/);
  if (parts.length >= 2) {
    const from = parts[0];
    const to = parts[1];
    const status = parts[2] || '301';
    redirectRules.push({ from, to, status });
    // Normalize exact from
    if (!from.includes('*') && !from.includes(':')) {
      exactRedirects.set(from, to);
      // Also map without or with trailing slash
      if (from.endsWith('/')) {
        exactRedirects.set(from.slice(0, -1), to);
      } else {
        exactRedirects.set(from + '/', to);
      }
    }
  }
}
console.log(`Loaded ${redirectRules.length} redirect rules (${exactRedirects.size} exact patterns) from ${redirectsPath}`);

// ==============================================================================
// 1. CANONICAL SANITY
// ==============================================================================
console.log('\n--- 1. CANONICAL SANITY AUDIT ---');
const canonicalResults = {
  totalChecked: 0,
  missing: [],
  mismatched: [],
  invalidFormat: [],
  passed: 0
};

for (const filePath of allHtmlFiles) {
  const normPath = filePath.split(path.sep).join('/');
  
  // Exclude static verification files (e.g., yandex verification)
  if (normPath.includes('yandex_')) continue;

  const content = fs.readFileSync(filePath, 'utf-8');
  canonicalResults.totalChecked++;

  // Check for redirect stub files generated by Astro (e.g. meta http-equiv="refresh")
  const isAstroRedirectFile = content.includes('http-equiv="refresh"') || content.includes("http-equiv='refresh'");

  const canonicalMatch = content.match(/<link\s+[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["'][^>]*>/i) ||
                         content.match(/<link\s+[^>]*href=["']([^"']+)["'][^>]*rel=["']canonical["'][^>]*>/i);

  if (!canonicalMatch) {
    canonicalResults.missing.push({ file: normPath, isAstroRedirectFile });
    continue;
  }

  const canonicalUrl = canonicalMatch[1];

  // Validate format: HTTPS, non-www fasttoolverse.com, ends with trailing slash
  if (!canonicalUrl.startsWith('https://fasttoolverse.com/')) {
    canonicalResults.invalidFormat.push({
      file: normPath,
      canonicalUrl,
      reason: 'Must start with https://fasttoolverse.com/'
    });
    continue;
  }

  if (!canonicalUrl.endsWith('/')) {
    canonicalResults.invalidFormat.push({
      file: normPath,
      canonicalUrl,
      reason: 'Must end with trailing slash'
    });
    continue;
  }

  // Determine expected canonical for actual page
  let expectedCanonical;
  if (normPath === 'dist/index.html') {
    expectedCanonical = 'https://fasttoolverse.com/';
  } else if (normPath === 'dist/404.html') {
    expectedCanonical = 'https://fasttoolverse.com/404/';
  } else {
    const slug = normPath.replace(/^dist\//, '').replace(/\/index\.html$/, '');
    expectedCanonical = `https://fasttoolverse.com/${slug}/`;
  }

  // In Astro redirect stubs, canonical points to target destination URL
  if (!isAstroRedirectFile && canonicalUrl !== expectedCanonical) {
    canonicalResults.mismatched.push({
      file: normPath,
      canonicalUrl,
      expectedCanonical
    });
  } else {
    canonicalResults.passed++;
  }
}

console.log(`Canonical Checked: ${canonicalResults.totalChecked}`);
console.log(`Passed: ${canonicalResults.passed}`);
console.log(`Missing Canonical: ${canonicalResults.missing.length}`);
console.log(`Invalid Format: ${canonicalResults.invalidFormat.length}`);
console.log(`Mismatched Canonical: ${canonicalResults.mismatched.length}`);

// ==============================================================================
// 2. ROBOTS META AUDIT
// ==============================================================================
console.log('\n--- 2. ROBOTS META AUDIT ---');
const robotsResults = {
  totalChecked: 0,
  noindexFiles: [],
  noindexInSitemapViolations: []
};

for (const filePath of allHtmlFiles) {
  const normPath = filePath.split(path.sep).join('/');
  if (normPath.includes('yandex_')) continue;

  const content = fs.readFileSync(filePath, 'utf-8');
  robotsResults.totalChecked++;

  const robotsMatch = content.match(/<meta\s+[^>]*name=["']robots["'][^>]*content=["']([^"']+)["'][^>]*>/i) ||
                      content.match(/<meta\s+[^>]*content=["']([^"']+)["'][^>]*name=["']robots["'][^>]*>/i);

  if (robotsMatch && robotsMatch[1].toLowerCase().includes('noindex')) {
    // Construct corresponding public URL
    let publicUrl;
    if (normPath === 'dist/index.html') {
      publicUrl = 'https://fasttoolverse.com/';
    } else if (normPath === 'dist/404.html') {
      publicUrl = 'https://fasttoolverse.com/404/';
    } else {
      const slug = normPath.replace(/^dist\//, '').replace(/\/index\.html$/, '');
      publicUrl = `https://fasttoolverse.com/${slug}/`;
    }

    robotsResults.noindexFiles.push({
      file: normPath,
      publicUrl,
      robotsContent: robotsMatch[1]
    });

    if (sitemapUrls.has(publicUrl)) {
      robotsResults.noindexInSitemapViolations.push({
        file: normPath,
        publicUrl,
        robotsContent: robotsMatch[1]
      });
    }
  }
}

console.log(`Total HTML files with noindex: ${robotsResults.noindexFiles.length}`);
console.log(`Noindex pages present in Sitemap: ${robotsResults.noindexInSitemapViolations.length}`);

// ==============================================================================
// 3. INTERNAL LINK AUDIT (Checking "Not found (404)" & "Page with redirect")
// ==============================================================================
console.log('\n--- 3. INTERNAL LINK AUDIT ---');

const linkResults = {
  totalAnchorsScanned: 0,
  uniqueInternalHrefs: new Set(),
  brokenLinks404: [],
  redirectLinks: []
};

// Helper function to resolve an internal href against dist filesystem and redirects
function checkInternalLink(sourceFile, href) {
  let cleanHref = href.trim();
  // Strip external domain if it points to fasttoolverse.com
  cleanHref = cleanHref.replace(/^https?:\/\/(www\.)?fasttoolverse\.com/, '');
  
  // Strip fragment and query
  cleanHref = cleanHref.split('#')[0].split('?')[0];
  if (!cleanHref) cleanHref = '/';

  // Ignore assets
  if (cleanHref.match(/\.(svg|png|jpg|jpeg|webp|ico|css|js|txt|xml|json|webmanifest)$/i)) {
    return;
  }

  linkResults.uniqueInternalHrefs.add(cleanHref);

  // Check 1: Does it point to a known redirect?
  // Check exact redirects
  const normHref = cleanHref.endsWith('/') ? cleanHref : cleanHref + '/';
  const unslashHref = cleanHref.endsWith('/') ? cleanHref.slice(0, -1) : cleanHref;

  let redirectTarget = exactRedirects.get(cleanHref) || exactRedirects.get(normHref) || exactRedirects.get(unslashHref);
  
  // Check wildcard/splat redirects
  if (!redirectTarget) {
    if (cleanHref.startsWith('/tools/')) {
      redirectTarget = 'Migrated /tools/ path';
    }
  }

  if (redirectTarget) {
    linkResults.redirectLinks.push({
      sourceFile,
      href,
      cleanHref,
      redirectTarget
    });
    return;
  }

  // Check missing trailing slash (unless root /)
  if (cleanHref !== '/' && !cleanHref.endsWith('/')) {
    linkResults.redirectLinks.push({
      sourceFile,
      href,
      cleanHref,
      redirectTarget: `${cleanHref}/ (Missing trailing slash 301)`
    });
    return;
  }

  // Check 2: Does it exist in dist/?
  // cleanHref will be like '/' or '/image-resizer/'
  let targetFilePath;
  if (cleanHref === '/') {
    targetFilePath = path.join(distDir, 'index.html');
  } else {
    const slugPath = cleanHref.replace(/^\/+/, '').replace(/\/+$/, '');
    targetFilePath = path.join(distDir, slugPath, 'index.html');
    if (!fs.existsSync(targetFilePath)) {
      // Check direct file (e.g. dist/404.html)
      const altFile = path.join(distDir, `${slugPath}.html`);
      if (fs.existsSync(altFile)) {
        targetFilePath = altFile;
      }
    }
  }

  if (!fs.existsSync(targetFilePath)) {
    linkResults.brokenLinks404.push({
      sourceFile,
      href,
      targetFilePath
    });
  }
}

for (const filePath of allHtmlFiles) {
  const normPath = filePath.split(path.sep).join('/');
  // We scan all user-facing HTML files
  // Exclude Astro redirect stub files (e.g. dist/tools/.../index.html) from internal link source
  // because they are only generated for fallback 301 redirects and are not indexed
  const content = fs.readFileSync(filePath, 'utf-8');
  if (content.includes('http-equiv="refresh"') || content.includes("http-equiv='refresh'")) {
    continue;
  }

  const anchorMatches = content.matchAll(/<a\s+[^>]*href=["']([^"']+)["'][^>]*>/gi);
  for (const match of anchorMatches) {
    linkResults.totalAnchorsScanned++;
    const href = match[1];

    // Filter for internal links
    const isExternal = href.startsWith('http://') || 
                       href.startsWith('https://') && !href.startsWith('https://fasttoolverse.com') && !href.startsWith('https://www.fasttoolverse.com') ||
                       href.startsWith('mailto:') ||
                       href.startsWith('tel:') ||
                       href.startsWith('javascript:');

    if (isExternal) continue;
    if (href.startsWith('#')) continue;

    checkInternalLink(normPath, href);
  }
}

console.log(`Total Anchor Tags Scanned: ${linkResults.totalAnchorsScanned}`);
console.log(`Unique Internal Page Routes: ${linkResults.uniqueInternalHrefs.size}`);
console.log(`Broken Internal Links (404): ${linkResults.brokenLinks404.length}`);
console.log(`Internal Links to Redirects: ${linkResults.redirectLinks.length}`);

// ==============================================================================
// 4. SITEMAP PURITY
// ==============================================================================
console.log('\n--- 4. SITEMAP PURITY AUDIT ---');
const sitemapPurityResults = {
  totalSitemapUrls: sitemapUrls.size,
  missingFiles: [],
  validCount: 0
};

for (const url of sitemapUrls) {
  const slug = url.replace('https://fasttoolverse.com/', '').replace(/\/$/, '');
  let filePath;
  if (!slug) {
    filePath = path.join(distDir, 'index.html');
  } else {
    filePath = path.join(distDir, slug, 'index.html');
  }

  if (!fs.existsSync(filePath)) {
    sitemapPurityResults.missingFiles.push({ url, filePath });
  } else {
    sitemapPurityResults.validCount++;
  }
}

console.log(`Sitemap URLs checked: ${sitemapPurityResults.totalSitemapUrls}`);
console.log(`Existing 200 HTML files: ${sitemapPurityResults.validCount}`);
console.log(`Missing files in dist: ${sitemapPurityResults.missingFiles.length}`);

// Output summary
console.log('\n======================================================');
console.log('                 FINAL AUDIT SUMMARY                  ');
console.log('======================================================');
console.log(`1. CANONICAL SANITY:           ${canonicalResults.missing.length === 0 && canonicalResults.invalidFormat.length === 0 && canonicalResults.mismatched.length === 0 ? 'PASS' : 'FAIL'}`);
console.log(`2. ROBOTS META AUDIT:          ${robotsResults.noindexInSitemapViolations.length === 0 ? 'PASS' : 'FAIL'}`);
console.log(`3. INTERNAL LINK INTEGRITY:    ${linkResults.brokenLinks404.length === 0 && linkResults.redirectLinks.length === 0 ? 'PASS' : 'FAIL'}`);
console.log(`4. SITEMAP PURITY:             ${sitemapPurityResults.missingFiles.length === 0 ? 'PASS' : 'FAIL'}`);
console.log('======================================================\n');

if (canonicalResults.missing.length > 0) {
  console.log('FAIL - Missing Canonical Tags:');
  console.dir(canonicalResults.missing, { depth: 2 });
}
if (canonicalResults.invalidFormat.length > 0) {
  console.log('FAIL - Invalid Canonical Format:');
  console.dir(canonicalResults.invalidFormat, { depth: 2 });
}
if (canonicalResults.mismatched.length > 0) {
  console.log('FAIL - Mismatched Canonical:');
  console.dir(canonicalResults.mismatched, { depth: 2 });
}
if (robotsResults.noindexInSitemapViolations.length > 0) {
  console.log('FAIL - Noindex in Sitemap:');
  console.dir(robotsResults.noindexInSitemapViolations, { depth: 2 });
}
if (linkResults.brokenLinks404.length > 0) {
  console.log('FAIL - Broken Internal Links (404):');
  console.dir(linkResults.brokenLinks404.slice(0, 20), { depth: 2 });
}
if (linkResults.redirectLinks.length > 0) {
  console.log('FAIL - Internal Links to Redirects:');
  // Group by href for readability
  const groupedRedirects = {};
  for (const r of linkResults.redirectLinks) {
    if (!groupedRedirects[r.href]) {
      groupedRedirects[r.href] = { count: 0, redirectTarget: r.redirectTarget, sampleSources: [] };
    }
    groupedRedirects[r.href].count++;
    if (groupedRedirects[r.href].sampleSources.length < 3) {
      groupedRedirects[r.href].sampleSources.push(r.sourceFile);
    }
  }
  console.dir(groupedRedirects, { depth: 3 });
}
if (sitemapPurityResults.missingFiles.length > 0) {
  console.log('FAIL - Missing Sitemap Files:');
  console.dir(sitemapPurityResults.missingFiles, { depth: 2 });
}
